def lighting_for_mood(mood: str, genre: str = "") -> str:
    """按段的情绪基调给光影描述；题材命中时先查题材覆盖表，再查通用表，都不中用默认。"""
    m = (mood or "").strip()
    if not m:
        return DEFAULT_LIGHTING
    tables = []
    key = match_genre(genre) if genre else GENERAL_GENRE
    if key in GENRE_LIGHTING:
        tables.append(GENRE_LIGHTING[key])
    tables.append(MOOD_LIGHTING)
    for table in tables:
        for words, lighting in table:
            if any(w in m for w in words):
                return lighting
    return DEFAULT_LIGHTING


def get_genre_rhythm_text(genre: str) -> str:
    """把题材节奏格式化成可注入提示词的段落；题材匹配不上时用“通用”。"""
    key = match_genre(genre)
    lines = GENRE_RHYTHM[key]
    title = f"【题材节奏：{key}】（在通用规则基础上，按本题材的节奏和镜头语言执行；表演层和情绪爆点优先落在“爽点清单”里的点上）"
    return title + "\n" + "\n".join(f"{i}. {line}" for i, line in enumerate(lines, 1))


def match_genre(genre: str) -> str:
    """精确匹配题材键；否则按 GENRE_RHYTHM 的字典顺序，逐个题材看键或它的别名是否包含在题材文本里
    （具体题材优先：“都市职场”→职场、“都市甜宠”→甜宠虐恋、“婆媳”→家庭伦理、“都市言情”→都市）；都不中返回“通用”。"""
    g = (genre or "").strip()
    if g in GENRE_RHYTHM:
        return g
    for key in GENRE_RHYTHM:
        if key == GENERAL_GENRE:
            continue
        if key in g or any(alias in g for alias, k in GENRE_ALIASES.items() if k == key):
            return key
    return GENERAL_GENRE
